#!/usr/bin/env bash
##
# Query the CN /meta endpoint for a list of PIDs and classify each one
# according to the wording of the 404 NotFound response, so the right
# repair script can be run against the right subset:
#
#   "No system metadata could be found for given PID: <pid>."
#     -> the object was never synced; d1cn_synchronize.sh (--force-sync) is
#        sufficient.
#
#   "No system metadata could be found for given PID: <pid>. The object
#    with the PID has been deleted from the node."
#     -> the object is in the purgatory state described in the README;
#        d1cn_force_accounting.sh is required.
#
# Requires: curl, xmlstarlet
#
# Requires a member node token file at ~/force_sync/token/NODE, where NODE is
# the nodeId of the MN (same convention as d1cn_synchronize.sh).
#
# By default, this script first runs d1cn_synchronize.sh (without --force-sync)
# to (re)generate the base ~/force_sync/pid/NODE list of PIDs on the MN that
# are not yet on the CN, then classifies that list. Pass --pid-file to
# classify an already-prepared list instead, or --use-existing-pid-list to
# classify the current ~/force_sync/pid/NODE without regenerating it.
#
# Usage:
#   d1cn_classify_pids.sh [options] <mn_id>
#
# Options:
#   --env ENV            Environment: dev, stage, sandbox, prod (default: prod)
#   --mn-base-url URL    Base URL of the MN, passed through to d1cn_synchronize.sh
#                        (looked up from the CN if omitted)
#   --pid-file FILE       Input list of PIDs to classify; skips running
#                         d1cn_synchronize.sh to generate the list
#                         (default: ~/force_sync/pid/NODE, generated by
#                         running d1cn_synchronize.sh first)
#   --use-existing-pid-list Classify the current ~/force_sync/pid/NODE
#                         instead of running d1cn_synchronize.sh to regenerate it
#   --sync-out FILE       Output file for PIDs that just need d1cn_synchronize.sh
#                         (default: ~/force_sync/pid/NODE.sync)
#   --force-out FILE      Output file for PIDs that need d1cn_force_accounting.sh
#                         (default: ~/force_sync/pid/NODE.force)
#   --sister-host HOST    SSH host for the sister CN, passed through to
#                         d1cn_force_accounting.sh (or set CN_SISTER_HOST)
#   -r, --run             After classifying, invoke d1cn_synchronize.sh
#                         --use-existing-pid-list --force-sync against
#                         --sync-out, then d1cn_force_accounting.sh against
#                         --force-out (both alongside this script)
#   --debug               Verbose logging to stderr
#   -h, --help            Show this help message and exit

set -euo pipefail

declare -A ENV_BASE_URL=(
  [dev]="https://cn-dev.test.dataone.org/cn"
  [stage]="https://cn-stage.test.dataone.org/cn"
  [sandbox]="https://cn-sandbox.test.dataone.org/cn"
  [prod]="https://cn.dataone.org/cn"
)

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)

ENV_NAME="prod"
MN_ID=""
MN_BASE_URL=""
PID_FILE=""
SYNC_OUT=""
FORCE_OUT=""
SISTER_HOST="${CN_SISTER_HOST:-}"
USE_EXISTING_PID_LIST=0
RUN_DOWNSTREAM=0
DEBUG=0

log() {
  echo "$(date '+%Y-%m-%d %H:%M:%S') INFO     $*" >&2
}

debug() {
  [[ "$DEBUG" -eq 1 ]] && echo "$(date '+%Y-%m-%d %H:%M:%S') DEBUG    $*" >&2
  return 0
}

usage() {
  grep '^#' "$0" | sed -e 's/^#//' -e 's/^ //'
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --env) ENV_NAME="$2"; shift 2 ;;
    --mn-base-url) MN_BASE_URL="$2"; shift 2 ;;
    --pid-file) PID_FILE="$2"; shift 2 ;;
    --use-existing-pid-list) USE_EXISTING_PID_LIST=1; shift ;;
    --sync-out) SYNC_OUT="$2"; shift 2 ;;
    --force-out) FORCE_OUT="$2"; shift 2 ;;
    --sister-host) SISTER_HOST="$2"; shift 2 ;;
    -r|--run) RUN_DOWNSTREAM=1; shift ;;
    --debug) DEBUG=1; shift ;;
    -h|--help) usage ;;
    -*) echo "Unknown option: $1" >&2; usage ;;
    *) MN_ID="$1"; shift ;;
  esac
done

if [[ -z "$MN_ID" ]]; then
  echo "Error: mn_id is required" >&2
  usage
fi

for tool in curl xmlstarlet; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "Error: required tool '$tool' not found in PATH" >&2
    exit 1
  }
done

CN_BASE_URL="${ENV_BASE_URL[$ENV_NAME]:-}"
if [[ -z "$CN_BASE_URL" ]]; then
  echo "Error: environment must be one of: ${!ENV_BASE_URL[*]}" >&2
  exit 1
fi

OUTDIR="$HOME/force_sync"
mkdir -p "$OUTDIR/token" "$OUTDIR/pid"
MN_NAME=${MN_ID##*:}
TOKEN_FILE="$OUTDIR/token/${MN_NAME}"

PID_FILE_SPECIFIED=0
[[ -n "$PID_FILE" ]] && PID_FILE_SPECIFIED=1
[[ -z "$PID_FILE" ]] && PID_FILE="$OUTDIR/pid/${MN_NAME}"
[[ -z "$SYNC_OUT" ]] && SYNC_OUT="$OUTDIR/pid/${MN_NAME}.sync"
[[ -z "$FORCE_OUT" ]] && FORCE_OUT="$OUTDIR/pid/${MN_NAME}.force"
UNKNOWN_OUT="$OUTDIR/pid/${MN_NAME}.unknown"

if [[ "$PID_FILE_SPECIFIED" -eq 0 && "$USE_EXISTING_PID_LIST" -eq 0 ]]; then
  log "Running d1cn_synchronize.sh to (re)generate $PID_FILE"
  sync_args=(--env "$ENV_NAME")
  [[ -n "$MN_BASE_URL" ]] && sync_args+=(--mn-base-url "$MN_BASE_URL")
  [[ "$DEBUG" -eq 1 ]] && sync_args+=(--debug)
  "$SCRIPT_DIR/d1cn_synchronize.sh" "${sync_args[@]}" "$MN_ID"
fi

if [[ ! -f "$PID_FILE" || ! -r "$PID_FILE" ]]; then
  echo "Error: PID list '$PID_FILE' does not exist or is not readable" >&2
  exit 1
fi

if [[ ! -r "$TOKEN_FILE" ]]; then
  echo "Error: TOKEN_FILE '$TOKEN_FILE' does not exist or is not readable" >&2
  exit 1
fi
TOKEN=$(tr -d '\r\n' < "$TOKEN_FILE")
if [[ -z "$TOKEN" ]]; then
  echo "Error: TOKEN_FILE '$TOKEN_FILE' is empty" >&2
  exit 1
fi

WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT

: > "$SYNC_OUT"
: > "$FORCE_OUT"
: > "$UNKNOWN_OUT"

xml_text() {
  # description text nodes are pretty-printed with a leading/trailing
  # newline (e.g. "<description>\nNo system metadata...\n</description>"),
  # so trim rather than take the first line, which would just be blank.
  xmlstarlet sel -t -m "$2" -v "." -n "$1" 2>/dev/null | tr '\n' ' ' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' || true
}

# classify_pid PID -> writes PID to SYNC_OUT, FORCE_OUT, or UNKNOWN_OUT
classify_pid() {
  local pid="$1"
  local resp_file="$WORKDIR/meta_${RANDOM}.xml"
  local http_code

  http_code=$(curl -sS -o "$resp_file" -w '%{http_code}' \
    -H "Authorization: Bearer ${TOKEN}" "${CN_BASE_URL}/v2/meta/${pid}" 2>/dev/null || echo "000")

  if [[ "$http_code" == "200" ]]; then
    log "$pid: CN already has system metadata; not adding to either list"
    return
  fi

  if [[ "$http_code" != "404" ]]; then
    log "$pid: unexpected HTTP $http_code from /meta; writing to $UNKNOWN_OUT for manual review"
    echo "$pid" >> "$UNKNOWN_OUT"
    return
  fi

  local description
  description=$(xml_text "$resp_file" "//*[local-name()='description']")
  debug "$pid: 404 response description: $description"

  if [[ "$description" == *"has been deleted from the node"* ]]; then
    debug "$pid: purgatory state (deleted from node) -> d1cn_force_accounting.sh"
    echo "$pid" >> "$FORCE_OUT"
  elif [[ "$description" == *"No system metadata could be found"* ]]; then
    debug "$pid: never synced -> d1cn_synchronize.sh"
    echo "$pid" >> "$SYNC_OUT"
  else
    log "$pid: 404 response did not match a known pattern; writing to $UNKNOWN_OUT for manual review"
    echo "$pid" >> "$UNKNOWN_OUT"
  fi
}

TOTAL=$(wc -l < "$PID_FILE" | tr -d ' ')
log "Classifying $TOTAL PID(s) from $PID_FILE against ${CN_BASE_URL}/v2/meta"

processed=0
while IFS= read -r pid; do
  [[ -z "$pid" ]] && continue
  processed=$((processed + 1))
  classify_pid "$pid"
  if [[ "$DEBUG" -eq 0 ]]; then
    printf '\rProgress: %d/%d' "$processed" "$TOTAL" >&2
  fi
done < "$PID_FILE"
if [[ "$DEBUG" -eq 0 ]]; then
  printf '\n' >&2
fi

log "$(wc -l < "$SYNC_OUT" | tr -d ' ') PID(s) need d1cn_synchronize.sh -> $SYNC_OUT"
log "$(wc -l < "$FORCE_OUT" | tr -d ' ') PID(s) need d1cn_force_accounting.sh -> $FORCE_OUT"
if [[ -s "$UNKNOWN_OUT" ]]; then
  log "$(wc -l < "$UNKNOWN_OUT" | tr -d ' ') PID(s) could not be classified -> $UNKNOWN_OUT"
fi

if [[ "$RUN_DOWNSTREAM" -eq 1 ]]; then
  if [[ -s "$SYNC_OUT" ]]; then
    log "Running d1cn_synchronize.sh for $(wc -l < "$SYNC_OUT" | tr -d ' ') PID(s)"
    "$SCRIPT_DIR/d1cn_synchronize.sh" --env "$ENV_NAME" --pid-file "$SYNC_OUT" --use-existing-pid-list --force-sync "$MN_ID"
  else
    log "No PIDs require d1cn_synchronize.sh; skipping"
  fi

  if [[ -s "$FORCE_OUT" ]]; then
    log "Running d1cn_force_accounting.sh for $(wc -l < "$FORCE_OUT" | tr -d ' ') PID(s)"
    force_args=(--env "$ENV_NAME" --pid-file "$FORCE_OUT")
    [[ -n "$SISTER_HOST" ]] && force_args+=(--sister-host "$SISTER_HOST")
    "$SCRIPT_DIR/d1cn_force_accounting.sh" "${force_args[@]}" "$MN_ID"
  else
    log "No PIDs require d1cn_force_accounting.sh; skipping"
  fi
fi
